import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { loadGarden, repositoryRoot } from './validate-garden.mjs';
import { buildTopicHubs, attachTopicHubs, branchId } from './build-topic-hubs.mjs';
const read = file => JSON.parse(readFileSync(path.join(repositoryRoot,file),'utf8'));
const { graph: base, publishedArticleIds } = loadGarden();
const config = read('content/garden/hub-integration.json');
const plan = read(config.outlineSource);
const datasets = Object.fromEntries(plan.legacyDataRefs.map(ref => [ref.file,read(ref.file)]));
const original = JSON.stringify(datasets);
const result = attachTopicHubs(base,repositoryRoot,publishedArticleIds);
const byId = new Map(result.nodes.map(node => [node.id,node]));
assert.equal(byId.size,result.nodes.length);
assert.equal(result.nodes.length,result.stats.nodes);
assert.equal(result.nodes.filter(n => n.parentId === 'hub:llm').length,12);
assert.equal(result.nodes.filter(n => n.kind === 'concept').length,base.stats.concepts);
for (const node of base.nodes) assert.equal(byId.get(node.id).parentId,node.parentId,'Canonical concept ownership changed');
assert.deepEqual(byId.get('branch:llm:mechanisms/attention/qkv').conceptRefs,['concept:qkv']);
assert.equal(byId.get('branch:llm:mechanisms/attention/qkv').articleBindings.length,0);
assert.equal(byId.get('hub:llm').articleBindings.length,0,'Hub should not be an alias for the overview');
assert.equal(byId.get('branch:llm:rankings/text-preference').embeddedArticleId,'arena-text');
assert.equal(byId.get('branch:llm:rankings/system-results').embeddedArticleId,'terminal-bench');
assert.equal(byId.get('branch:llm:pricing/offers').embeddedArticleId,'model-api-prices');
assert.equal(result.hubResources['terminal-bench'].subjectRole,'agent-system-evaluation');
assert.equal(JSON.stringify(datasets),original,'Navigation build modified facts');
const mapped = new Set(result.nodes.flatMap(n => n.resourceRefs ?? []).map(r => r.articleId));
assert.equal(mapped.size,publishedArticleIds.size);
for (const id of publishedArticleIds) assert.ok(mapped.has(id),`Missing article resource ${id}`);
for (const node of result.nodes) {
  if (node.parentId) assert.ok(byId.has(node.parentId));
  const seen = new Set(); let cursor = node;
  while (cursor?.parentId) { assert.ok(!seen.has(cursor.id),'Navigation cycle'); seen.add(cursor.id); cursor=byId.get(cursor.parentId); }
}
assert.equal(new Set(result.edges.map(edge=>edge.id)).size,result.edges.length,'Duplicate edge');
for (const edge of result.edges) assert.ok(byId.has(edge.source)&&byId.has(edge.target));
assert.equal(byId.get(branchId('hub:video','tutorials')).resourceRefs[0].articleId,'apple-style-premium-product-video');
assert.equal(byId.get('hub:rag').articleBindings.length,0);
assert.equal(result.nodes.filter(n=>n.parentId==='hub:rag').length,0,'Do not fill other hubs with empty template sections');
let negatives=0;
const reject = edit => { const p=structuredClone(plan), c=structuredClone(config), d=structuredClone(datasets); edit(p,c,d); assert.throws(()=>buildTopicHubs(base,p,c,publishedArticleIds,d)); negatives++; };
reject((p,c)=>c.enabledHubs.push('hub:missing'));
reject((p,c)=>c.enabledHubs.push(c.enabledHubs[0]));
reject(p=>p.hubOutlines['hub:llm'][0].children.push({id:'bad',label:'bad',conceptRefs:['concept:missing']}));
reject(p=>p.hubOutlines['hub:llm'].push(structuredClone(p.hubOutlines['hub:llm'][0])));
reject((p,c)=>c.resourcePlacements.push({hubId:'hub:llm',path:'missing',articleId:'overview',role:'test'}));
reject((p,c)=>c.resourcePlacements.push({hubId:'hub:llm',path:'orientation',articleId:'missing',role:'test'}));
reject((p,c,d)=>d['content/data/benchmarks.json'].benchmarks=[]);
const report={status:'pass',suite:'topic-hub-navigation',...result.stats,mappedResources:mapped.size,negativeCases:negatives,canonicalConceptsUnchanged:true,factDatesUnchanged:true};
mkdirSync(path.join(repositoryRoot,'test-results'),{recursive:true});
writeFileSync(path.join(repositoryRoot,'test-results/topic-hubs-contract.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
